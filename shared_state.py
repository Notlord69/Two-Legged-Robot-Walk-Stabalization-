# TELEMETRY RING BUFFER  — zero-allocation, numpy-backed
# ============================================================================

class TelemetryRingBuffer:
    """
    Pre-allocated numpy ring buffer for zero-allocation telemetry.

    Each row stores one telemetry sample:
    [timestamp, cycle, error_code, com_x, com_y, com_z,
     left_contact_state, right_contact_state, stability_status,
     left_force, right_force, stability_margin, compute_time_us,
     extra_0, extra_1, extra_2]

    Producer (100Hz): writes raw floats via write().
    Consumer (10Hz): reads via read_batch().
    """
    COLS = 16

    def __init__(self, capacity: int = 2048):
        self._buf = np.zeros((capacity, self.COLS), dtype=np.float64)
        self._capacity = capacity
        self._write_idx = 0  # monotonic, consumer uses modulo
        self._read_idx = 0

    def write(self, row: np.ndarray) -> None:
        """O(1), zero-alloc write. Overwrites oldest on full."""
        idx = self._write_idx % self._capacity
        self._buf[idx, :] = row
        self._write_idx += 1

    def read_batch(self) -> np.ndarray:
        """Returns unread rows (may be empty). Consumer call."""
        w = self._write_idx
        r = self._read_idx
        if w == r:
            return np.empty((0, self.COLS))
        # Handle wraparound
        count = min(w - r, self._capacity)
        start = r % self._capacity
        end = w % self._capacity
        self._read_idx = w
        if end > start:
            return self._buf[start:end].copy()
        else:
            return np.vstack([self._buf[start:], self._buf[:end]])


