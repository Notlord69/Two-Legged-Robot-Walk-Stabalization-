class Siclo1State:
    """
    Central shared state object.

    ALL modules read and write through this object.
    Provides thread-safe access to system state.

    Usage:
        from shared_state import shared_state

        # Read
        com = shared_state.com_position

        # Write
        shared_state.set_stability_status(StabilityStatus.STABLE)
    """

    def __init__(self):
        """Initialize shared state with default values"""
        self._lock = threading.Lock()

        # ====================================================================
        # TIMING STATE (Written by main.py)
        # ====================================================================
        self.sim_time: float = 0.0
        self.cycle_count: int = 0
        self.last_dt: float = 0.01   # 100 Hz target
        self.timing_violations: int = 0

        # ====================================================================
        # ROBOT PHYSICAL STATE (Written by main.py from PyBullet)
        # ====================================================================
        # Base state
        self.base_position: np.ndarray = np.array([0.0, 0.0, 0.8806])  # torso COM z from URDF
        self.base_orientation: np.ndarray = np.array([0.0, 0.0, 0.0, 1.0])
        self.base_velocity: np.ndarray = np.zeros(3)
        self.base_angular_velocity: np.ndarray = np.zeros(3)

        # ── URDF joint name mapping ──────────────────────────────────────────
        # Keys used throughout the codebase must match URDF <joint name="...">
        # exactly.  See URDF_JOINT_NAMES below for the full canonical list.
        self.joint_positions: Dict[str, float] = {}
        self.joint_velocities: Dict[str, float] = {}
        self.joint_torques: Dict[str, float] = {}

        self.target_angle = 0.0

        # Link positions (from forward kinematics)
        self.link_positions: Dict[str, np.ndarray] = {}

        # ====================================================================
        # LOAD STATE (Written by main.py or load manager)
        # ====================================================================
        self.current_load_mass: float = 0.0   # 0–5 kg variable payload
        # Backpack attachment offset from torso COM.
        # URDF base_link COM z = 0.8806 m; backpack sits ~0.10 m above that.
        self.load_com_offset: np.ndarray = np.array([0.0, 0.0, 0.10])

        # ====================================================================
        # CONTACT STATE (Written by perception.py)
        # ====================================================================
        self.left_foot_contact_state: ContactState = ContactState.NO_CONTACT
        self.right_foot_contact_state: ContactState = ContactState.NO_CONTACT

        # --- 3-Tick Validation & Flat Foot ---
        self.left_contact_ticks: int = 0
        self.right_contact_ticks: int = 0
        self.left_foot_flat: bool = False
        self.right_foot_flat: bool = False

        self.left_foot_force: float = 0.0
        self.right_foot_force: float = 0.0

        self.left_contact_points: List[np.ndarray] = []
        self.right_contact_points: List[np.ndarray] = []

        # Foot positions — lateral (Y) initialised from URDF ankle positions:
        #   Left  ankle Y ≈ +0.225 m,  Right ankle Y ≈ +0.196 m
        #   Mid-point Y  ≈  0.211 m;  half-separation ≈ 0.014 m each side.
        #   Kept as ±0.10 m defaults for symmetry until FK/PyBullet populates them.
        self.left_foot_position: np.ndarray  = np.array([-0.1, 0.0, 0.0])
        self.right_foot_position: np.ndarray = np.array([ 0.1, 0.0, 0.0])

        self.left_foot_velocity: np.ndarray  = np.zeros(3)
        self.right_foot_velocity: np.ndarray = np.zeros(3)

        self.left_foot_slip_detected: bool  = False
        self.right_foot_slip_detected: bool = False

        self.left_contact_start_time: float  = 0.0
        self.right_contact_start_time: float = 0.0

        # ====================================================================
        # STABILITY STATE (Written by stability.py)
        # ====================================================================
        self.com_position: np.ndarray = np.array([0.0, 0.0, 0.8806])
        self.com_velocity: np.ndarray = np.zeros(3)

        self.stability_status: StabilityStatus = StabilityStatus.STABLE
        self.is_unstable: bool = False

        self.support_polygon: Optional[Polygon] = None
        self.stability_margin: float = 0.0
        self.current_safety_margin: float = 0.02   # metres

        # ====================================================================
        # RECOVERY STATE (Written by recovery.py)
        # ====================================================================
        self.recovery_action: RecoveryAction = RecoveryAction.NONE
        self.recovery_active: bool = False
        self.recovery_reason: str = ""

        self.current_step_start_time: float  = 0.0
        self.step_timeout_threshold: float   = 3.0   # seconds

        # ====================================================================
        # KINEMATICS STATE (Written by kinematics.py, read by WBC / HeartBeat)
        # ====================================================================
        # IK output angles, URDF-signed and ready for joint targets (rad).
        # Tuple order: (hip_pitch, knee, ankle) per side.
        self.ik_left_angles:  tuple = (0.0, 0.0, 0.0)
        self.ik_right_angles: tuple = (0.0, 0.0, 0.0)

        # Swing trajectory state — persists across 100 Hz loop iterations.
        self.swing_phase: float = 0.0            # normalized phase ∈ [0, 1]
        self.swing_foot_target: tuple = (0.0, 0.0, 0.0)
        # m, (x, y, z) touchdown target relative to hip-pitch joint, world frame

        # Feedforward torso pitch correction from angular momentum (rad).
        self.torso_pitch_correction: float = 0.0  # rad, applied to torso pitch joint

        # Per-leg foot targets (m, world frame).
        # Written by gait planner; read by DebugVisualizer.
        # Default (0,0,0) = no active target; visualiser skips red line.
        self.left_foot_target:  tuple = (0.0, 0.0, 0.0)
        self.right_foot_target: tuple = (0.0, 0.0, 0.0)

        # ====================================================================
        # SYSTEM HEALTH
        # ====================================================================
        self.system_status: SystemStatus = SystemStatus.NOMINAL
        self.emergency_stop_triggered: bool = False
        self.freeze_robot: bool = False

        self.error_messages: List[str] = []

        # ====================================================================
        # PRE-ALLOCATED TELEMETRY BUS (Written by 100Hz producer)
        # ====================================================================
        self.telemetry = TelemetryRingBuffer(capacity=2048)
        self._telem_row = np.zeros(TelemetryRingBuffer.COLS, dtype=np.float64)  # scratch row

        # Pre-allocated error ring (numeric codes, no strings)
        self._error_codes = np.zeros(256, dtype=np.int32)
        self._error_timestamps = np.zeros(256, dtype=np.float64)
        self._error_write_idx = 0

    # ========================================================================
    # THREAD-SAFE SETTERS
    # ========================================================================

    def set_stability_status(self, status: StabilityStatus, margin: float = 0.0):
        with self._lock:
            self.stability_status = status
            self.is_unstable = (status == StabilityStatus.UNSTABLE)
            self.stability_margin = margin

    def set_contact_state(self, foot: str, state: ContactState):
        with self._lock:
            if foot == 'left':
                self.left_foot_contact_state = state
            elif foot == 'right':
                self.right_foot_contact_state = state

    def set_slip_detection(self, foot: str, slip: bool):
        with self._lock:
            if foot == 'left':
                self.left_foot_slip_detected = slip
            elif foot == 'right':
                self.right_foot_slip_detected = slip

    def set_recovery_action(self, action: RecoveryAction, reason: str = ""):
        with self._lock:
            self.recovery_action = action
            self.recovery_active = (action != RecoveryAction.NONE)
            self.recovery_reason = reason

    def increment_timing_violations(self):
        with self._lock:
            self.timing_violations += 1
            if self.timing_violations > 10:
                self.freeze_robot = True

    def add_error_code(self, code: int) -> None:
        """O(1) zero-alloc error logging. No strings, no lock.
        Legal on the 100Hz fast path."""
        idx = self._error_write_idx % 256
        self._error_codes[idx] = code
        self._error_timestamps[idx] = self.sim_time
        self._error_write_idx += 1

    def add_error(self, msg: str):
        """@deprecated — cold-path ONLY (init, shutdown, test code).
        NEVER call from the 100Hz hot loop."""
        warnings.warn(
            "add_error(str) is deprecated on the hot path. "
            "Use add_error_code(int) instead.",
            DeprecationWarning,
            stacklevel=2,
        )
        with self._lock:
            self.error_messages.append(f"[t={self.sim_time:.3f}] {msg}")
            if len(self.error_messages) > 100:
                self.error_messages = self.error_messages[-50:]

    # ========================================================================
    # CONVENIENCE QUERIES
    # ========================================================================

    def get_confirmed_contact_points(self) -> List[np.ndarray]:
        points = []
        if self.left_foot_contact_state == ContactState.CONTACT_CONFIRMED:
            if self.left_contact_points:
                points.extend([p.copy() for p in self.left_contact_points])
            else:
                points.append(self.left_foot_position.copy())
        if self.right_foot_contact_state == ContactState.CONTACT_CONFIRMED:
            if self.right_contact_points:
                points.extend([p.copy() for p in self.right_contact_points])
            else:
                points.append(self.right_foot_position.copy())
        return points

    def both_feet_in_contact(self) -> bool:
        return (self.left_foot_contact_state  == ContactState.CONTACT_CONFIRMED and
                self.right_foot_contact_state == ContactState.CONTACT_CONFIRMED)

    def any_foot_slipping(self) -> bool:
        return self.left_foot_slip_detected or self.right_foot_slip_detected

    def get_step_duration(self) -> float:
        return self.sim_time - self.current_step_start_time

    # ========================================================================
    # DIAGNOSTICS
    # ========================================================================

    def get_diagnostics(self) -> Dict:
        return {
            'sim_time':          self.sim_time,
            'cycle_count':       self.cycle_count,
            'last_dt':           self.last_dt,
            'timing_violations': self.timing_violations,
            'load_mass':         self.current_load_mass,
            'com_position':      self.com_position.tolist(),
            'com_velocity':      self.com_velocity.tolist(),
            'stability_status':  self.stability_status.name,
            'is_unstable':       self.is_unstable,
            'stability_margin':  self.stability_margin,
            'safety_margin':     self.current_safety_margin,
            'left_contact':      self.left_foot_contact_state.name,
            'right_contact':     self.right_foot_contact_state.name,
            'left_ticks':        self.left_contact_ticks,
            'right_ticks':       self.right_contact_ticks,
            'left_flat':         self.left_foot_flat,
            'right_flat':        self.right_foot_flat,
            'left_force':        self.left_foot_force,
            'right_force':       self.right_foot_force,
            'left_slip':         self.left_foot_slip_detected,
            'right_slip':        self.right_foot_slip_detected,
            'recovery_action':   self.recovery_action.name,
            'recovery_active':   self.recovery_active,
            'recovery_reason':   self.recovery_reason,
            'system_status':     self.system_status.name,
            'emergency_stop':    self.emergency_stop_triggered,
            'freeze_robot':      self.freeze_robot,
            'errors':            len(self.error_messages),
        }

    def print_status(self, verbose: bool = False):
        print(f"\n{'='*70}")
        print(f"SICLO1 STATE @ t={self.sim_time:.3f}s (Cycle {self.cycle_count})")
        print(f"{'='*70}")
        print(f"\n[SYSTEM]  {self.system_status.name}  violations={self.timing_violations}  frozen={self.freeze_robot}")
        print(f"\n[STABILITY]  {self.stability_status.name}")
        print(f"  COM: [{self.com_position[0]:.3f}, {self.com_position[1]:.3f}, {self.com_position[2]:.3f}]")
        print(f"  Margin: {self.stability_margin:.4f} m  (safety: {self.current_safety_margin:.4f} m)")
        print(f"  Load: {self.current_load_mass:.1f} kg")
        print(f"\n[CONTACT]")
        print(f"  Left : {self.left_foot_contact_state.name:<20} F={self.left_foot_force:6.1f} N  slip={self.left_foot_slip_detected}")
        print(f"  Right: {self.right_foot_contact_state.name:<20} F={self.right_foot_force:6.1f} N  slip={self.right_foot_slip_detected}")
        print(f"\n[RECOVERY]  {self.recovery_action.name}  step_dur={self.get_step_duration():.2f}s")
        if self.recovery_active:
            print(f"  Reason: {self.recovery_reason}")
        if verbose and self.error_messages:
            print(f"\n[ERRORS]")
            for msg in self.error_messages[-5:]:
                print(f"  {msg}")
        print(f"{'='*70}\n")

    def reset(self):
        with self._lock:
            self.sim_time = 0.0
            self.cycle_count = 0
            self.timing_violations = 0
            self.stability_status = StabilityStatus.STABLE
            self.is_unstable = False
            self.left_foot_contact_state  = ContactState.NO_CONTACT
            self.right_foot_contact_state = ContactState.NO_CONTACT
            self.left_contact_ticks = 0
            self.right_contact_ticks = 0
            self.left_foot_flat = False
            self.right_foot_flat = False
            self.left_contact_points.clear()
            self.right_contact_points.clear()
            self.recovery_action  = RecoveryAction.NONE
            self.recovery_active  = False
            self.system_status    = SystemStatus.NOMINAL
            self.emergency_stop_triggered = False
            self.freeze_robot     = False
            self.error_messages.clear()
            # Reset telemetry ring
            self.telemetry = TelemetryRingBuffer(capacity=2048)
            self._telem_row[:] = 0.0
            self._error_codes[:] = 0
            self._error_timestamps[:] = 0.0
            self._error_write_idx = 0


